// Turns dist/ into an installable offline web app (PWA): the game opens without a network after the
// first visit and can be "installed" to a phone's home screen. Run: npm run build:web
//
// Only for your own site (GitHub Pages, itch.io, a server). Not for game portals: they run the game in
// their own frame and forbid service workers — use `npm run zip` for them.
//
// Writes dist/manifest.webmanifest, dist/icon-192.png, dist/icon-512.png and dist/sw.js
// (cache-first for every file of this build; a new build gets a new cache name, the old one is removed),
// and adds the manifest link and the service worker registration to dist/index.html.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, relative, sep } from "node:path"

import { PNG } from "pngjs"

const DIST = "dist"
const NAME = "Моя игра"
const COLOR = "#1d1630"
/** Pixel-art icon source, scaled up without smoothing */
const ICON = "public/assets/sprites/coin.png"

const files = []
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) walk(path)
    else files.push(relative(DIST, path).split(sep).join("/"))
  }
}
walk(DIST)
if (!files.includes("index.html")) {
  console.error("dist/index.html not found — run the build first")
  process.exit(1)
}

// ---------- icons: the sprite scaled with nearest-neighbour onto a square background ----------
const source = PNG.sync.read(readFileSync(ICON))
const icon = (size) => {
  const out = new PNG({ width: size, height: size })
  const bg = [0x1d, 0x16, 0x30, 0xff]
  const scale = Math.floor((size * 0.7) / Math.max(source.width, source.height))
  const ox = Math.floor((size - source.width * scale) / 2)
  const oy = Math.floor((size - source.height * scale) / 2)
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const sx = Math.floor((x - ox) / scale)
      const sy = Math.floor((y - oy) / scale)
      const inside = sx >= 0 && sy >= 0 && sx < source.width && sy < source.height
      const i = (y * size + x) * 4
      const s = inside ? (sy * source.width + sx) * 4 : -1
      const alpha = s >= 0 ? source.data[s + 3] / 255 : 0
      for (let c = 0; c < 3; c++)
        out.data[i + c] = Math.round(bg[c] * (1 - alpha) + (s >= 0 ? source.data[s + c] : 0) * alpha)
      out.data[i + 3] = 255
    }
  }
  writeFileSync(join(DIST, `icon-${size}.png`), PNG.sync.write(out))
}
icon(192)
icon(512)

// ---------- manifest ----------
const manifest = {
  name: NAME,
  short_name: NAME,
  start_url: "./",
  scope: "./",
  display: "fullscreen",
  orientation: "landscape",
  background_color: COLOR,
  theme_color: COLOR,
  icons: [
    { src: "icon-192.png", sizes: "192x192", type: "image/png" },
    { src: "icon-512.png", sizes: "512x512", type: "image/png", purpose: "any maskable" },
  ],
}
writeFileSync(join(DIST, "manifest.webmanifest"), JSON.stringify(manifest, null, 2))

// ---------- service worker: precache the whole build ----------
const assets = ["./", ...files.filter((f) => f !== "sw.js").map((f) => `./${f}`), "./icon-192.png", "./icon-512.png"]
const version = Date.now().toString(36)
const sw = `// Generated by scripts/pwa.mjs — do not edit
const CACHE = "game-${version}"
const ASSETS = ${JSON.stringify([...new Set(assets)])}
self.addEventListener("install", (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting())))
self.addEventListener("activate", (e) =>
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())),
)
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)))
})
`
writeFileSync(join(DIST, "sw.js"), sw)

// ---------- index.html: manifest + registration ----------
const indexPath = join(DIST, "index.html")
let html = readFileSync(indexPath, "utf8")
if (!html.includes("manifest.webmanifest")) {
  html = html.replace(
    "</head>",
    `  <link rel="manifest" href="./manifest.webmanifest" />\n    <meta name="theme-color" content="${COLOR}" />\n  </head>`,
  )
  html = html.replace(
    "</body>",
    `  <script>if ("serviceWorker" in navigator) addEventListener("load", () => navigator.serviceWorker.register("./sw.js"))</script>\n  </body>`,
  )
  writeFileSync(indexPath, html)
}
console.log(`PWA: ${assets.length} files cached offline, manifest and icons in ${DIST}/`)
