  function makeMathQuestion(level, tx) {
    const kind = randInt(0, 2);
    let a, b, text, answer;
    if (kind === 0) {
      a = randInt(2, 10 + level * 15); b = randInt(2, 10 + level * 15);
      text = a + ' + ' + b + ' = ?'; answer = a + b;
    } else if (kind === 1) {
      a = randInt(5, 15 + level * 15); b = randInt(1, a);
      text = a + ' − ' + b + ' = ?'; answer = a - b;
    } else {
      a = randInt(2, 5 + level * 2); b = randInt(2, 9);
      text = a + ' × ' + b + ' = ?'; answer = a * b;
    }
    const wrong = new Set();
    while (wrong.size < 3) {
      const w = answer + randInt(-10, 10);
      if (w !== answer && w >= 0) wrong.add(w);
    }
    return { text: text, hint: tx.mathHint, answer: String(answer), options: shuffle([answer].concat([...wrong])).map(String) };
  }

  function makeQuestion(subject, level, tx) {
    if (subject === 'rus') {
      const [word, i] = pick(RUS_WORDS);
      const letter = word[i] === 'Ё' ? 'Е' : word[i];
      const wrong = shuffle(VOWELS.filter(v => v !== letter)).slice(0, 3);
      return { text: word.slice(0, i) + '_' + word.slice(i + 1), hint: tx.rusHint, answer: letter, options: shuffle([letter].concat(wrong)) };
    }
    if (subject === 'eng') {
      const [word, tr] = pick(ENG_WORDS);
      const wrong = shuffle(ENG_WORDS.filter(w => w[1] !== tr)).slice(0, 3).map(w => w[1]);
      return { text: word, hint: tx.engHint, answer: tr, options: shuffle([tr].concat(wrong)) };
    }
    if (subject === 'hist') {
      const [text, answer, wrong] = pick(HISTORY);
      return { text: text, hint: tx.histHint, answer: answer, options: shuffle([answer].concat(wrong)) };
    }
    return makeMathQuestion(level, tx);
  }

